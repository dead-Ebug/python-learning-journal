# print() is a built-in Python function.
# Its job is to display information in the terminal.

# Parentheses () are used to pass information
# (called an argument) into the print() function.

# Quotation marks "" tell Python that the content
# inside them is text (a string).


print("Hello, world!")
# Displays the text Hello, world! in the terminal.



print("I am learning Python")
# Displays another message in the terminal.


# ==================================================
# NOTES:
#
# 1. print = the function that displays information.
# 2. () = holds the information we give to print().
# 3. "" = marks text as a string.
# 4. # = starts a comment.
#
# IMPORTANT:
# Comments are notes for humans.
# Python ignores comments when running the program.
